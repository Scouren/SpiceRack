#!/usr/bin/env bash
# Regenerates params.txt: every parameter of every module VACASK ships, as VACASK lists them.
# Run inside `nix develop .#testing` from this directory: ./params.sh > params.txt
# Provenance: `print model(...)` (every parameter) and `print instance(...)` (the instance
# parameters) of the pinned VACASK (VD cmd-print), and the `aliasparam` lines of each module's
# Verilog-A source in the same store (an alias is a second name VACASK accepts).
set -euo pipefail
store=$(dirname "$(dirname "$(readlink -f "$(command -v vacask)")")")
src="$store/src/vacask/devices"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
echo "# Generated by params.sh from $(basename "$store"); do not edit."
echo "# <module> i|m|a <names>: instance parameters, model-only parameters, aliases (alias=target)."
while read -r module file terminals va; do
  printf 'p\nload "%s"\nmodel m %s\nx1 (%s) m\ncontrol\n  print model("m")\n  print instance("x1")\nendc\n' \
    "$file" "$module" "${terminals//_/ }" > "$work/deck.sim"
  (cd "$work" && vacask deck.sim > out.txt 2>&1) || true
  model=$(awk '/^Osdi device model/{f=1;next} /^Osdi device instance/{f=0} f && /^    [^ ]+ = /{print $1}' "$work/out.txt")
  inst=$(awk '/^Osdi device instance/{f=1;next} /Output variables/{f=0} f && /^    [^ ]+ = /{print $1}' "$work/out.txt")
  test -n "$model" || { echo "no listing for $module" >&2; exit 1; }
  echo "$module i $(echo "$inst" | tr '\n' ' ')"
  echo "$module m $(comm -23 <(echo "$model" | sort) <(echo "$inst" | sort) | tr '\n' ' ')"
  aliases=$(grep -ho 'aliasparam *[A-Za-z_0-9]* *= *[A-Za-z_0-9]*' $src/$va 2>/dev/null \
    | sed 's/aliasparam *//; s/ *= */=/' | tr 'A-Z' 'a-z' | grep -v '=paramname$' | sort -u | tr '\n' ' ' || true)
  echo "$module a $aliases"
done <<'LIST'
