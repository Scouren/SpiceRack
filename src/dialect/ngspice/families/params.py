"""Regenerates params.txt from the ngspice-45 source tree (argv[1]: the unpacked tarball).

Each device's settable parameters (IOP*/IP* rows; OP* rows are read-only) of its model table
(`*mPTable[]`) and its instance table (`*pTable[]`): `create_model` (inpgmod.c) accepts a model
parameter, or a settable instance parameter as the instances' default, but skips `level` and
`m` that are no model parameter before it looks at the instance table. Only
lowercase keywords: ngspice lowercases the deck and compares with strcmp. jfet2's model rows
are the `PARAM(...)` lines of `jfet2parm.h`, which `jfet2.c` includes inside the table with
`PARAM` defined as `IOP`. Any other preprocessor line inside a table is reported on stderr (none
in ngspice-45 but B4SOI's `#ifdef B4SOI_DEBUG_OUT` around three OP rows).

    python3 -I params.py /path/to/ngspice-45 > params.txt
"""

import pathlib
import re
import sys

DEVICES = (
    "res cap ind sw csw dio bjt vbic hicum2 jfet jfet2 mes mesa hfet1 hfet2 mos1 mos2 mos3 "
    "mos6 mos9 bsim1 bsim2 bsim3v0 bsim3v1 bsim3v32 bsim3 bsim4v5 bsim4v6 bsim4v7 bsim4 "
    "bsim3soi_fd bsim3soi_dd bsim3soi_pd bsimsoi soi3 hisim2 hisimhv1 hisimhv2 vdmos urc ltra "
    "txl cpl"
).split()
HEAD = re.compile(r"^IFparm\s+(\w+?)(mP|p)Table\s*\[\s*\]\s*=\s*\{")
ROW = re.compile(r"^\s*(I(?:OP|P)\w*|PARAM\w*)\s*\(\s*\"([^\"]+)\"", re.M)
INCLUDE = re.compile(r'^#include "(\w+\.h)"', re.M)


def main() -> None:
    root = pathlib.Path(sys.argv[1]) / "src/spicelib/devices"
    print("# generated by params.py from ngspice-45/src/spicelib/devices: per device, the names a")
    print("# .model card sets (tarball sha256 f1aad8abac2828a7b71da66411de8e406524e75f3066e46755439c490442d734)")
    for dev in DEVICES:
        tables: dict[tuple[str, str], str] = {}
        for c in sorted((root / dev).glob("*.c")):
            lines = c.read_text(errors="replace").splitlines()
            for k, line in enumerate(lines):
                m = HEAD.match(line)
                if m:
                    end = next(j for j in range(k, len(lines)) if lines[j].strip() == "};")
                    tables[(m.group(1), m.group(2))] = "\n".join(lines[k + 1 : end])
        # the device's pair: a model table and the instance table of the same prefix
        (prefix,) = [p for (p, kind) in tables if kind == "mP"]
        names: set[str] = set()
        for kind in ("mP", "p"):
            body = tables[(prefix, kind)]
            # jfet2: the model rows are PARAM(...) lines of an included header, each IOP*
            for h in INCLUDE.findall(body):
                body += "\n" + (root / dev / h).read_text()
            if re.search(r"^\s*#(?!include|define|undef|ifndef|ifdef B4SOI_DEBUG_OUT|endif)", body, re.M):
                print(f"{dev}: {prefix}{kind}Table: preprocessor line", file=sys.stderr)
            rows = {k for _, k in ROW.findall(body) if k == k.lower()}
            # create_model skips `level` and `m` before it looks at the instance table
            names.update(rows if kind == "mP" else rows - {"level", "m"})
        print(dev, " ".join(sorted(names)))


main()
