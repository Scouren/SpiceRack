"""Regenerates outputs.txt from the ngspice-45 source tree (argv[1]: the unpacked tarball).

Each device's instance outputs: the rows of its instance table (`*pTable[]`) a `@dev[name]`
reads, `OP*` (read-only) and `IOP*` (settable and readable); `IP*` rows are set-only. Only
lowercase keywords (ngspice lowercases the deck). One line per device directory: the name, then
the sorted output names.

    python3 -I outputs.py /path/to/ngspice-45 > outputs.txt
"""

import pathlib
import re
import sys

HEAD = re.compile(r"^IFparm\s+(\w+?)pTable\s*\[\s*\]\s*=\s*\{")
ROW = re.compile(r"^\s*(I?OP\w*)\s*\(\s*\"([^\"]+)\"", re.M)


def main() -> None:
    root = pathlib.Path(sys.argv[1]) / "src/spicelib/devices"
    print("# generated by outputs.py from ngspice-45/src/spicelib/devices: per device, the names")
    print("# @dev[name] reads (instance OP and IOP rows)")
    for d in sorted(p for p in root.iterdir() if p.is_dir()):
        names: set[str] = set()
        for c in sorted(d.glob("*.c")):
            lines = c.read_text(errors="replace").splitlines()
            for k, line in enumerate(lines):
                if HEAD.match(line) and "mPTable" not in line:
                    end = next(j for j in range(k, len(lines)) if lines[j].strip().startswith("};"))
                    body = "\n".join(lines[k + 1 : end])
                    names.update(n for _, n in ROW.findall(body) if n == n.lower())
        if names:
            print(d.name, " ".join(sorted(names)))


main()
