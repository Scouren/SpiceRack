def deck(title="rc", globals=(), functions=(), loads=(), subckts=(), top=(), bench=()):
    """An ngspice-given deck, in `src/python/deck.rs::source`'s order:
    title, `.global`, `.func`, loads (a `.control`/`pre_osdi`/`.endc`
    block, `store.rs::with_loads`'s form), subcircuit defs, the top body,
    the bench. Statement order past that does not affect parsing (each
    line is read on its own), so callers may otherwise list lines freely.
    """
    lines = [title]
    if globals:
        lines.append(".global " + " ".join(globals))
    lines.extend(functions)
    if loads:
        lines.append(".control")
        lines.extend(f"pre_osdi {p}" for p in loads)
        lines.append(".endc")
    for sc in subckts:
        lines.extend(sc)
    lines.extend(top)
    lines.extend(bench)
    lines.append(".end")
    return "\n".join(lines) + "\n"


