def ps_():
    return ps()


def _code(tb, target):
    """A written cell's full netlist bytes, or its sorted refusal code
    set (api-parity.md §3: "for a written cell, the full netlist
    bytes")."""
    try:
        return tb.netlist(target)
    except RuntimeError as e:
        if "iverilog not found" in str(e):
            return NEEDS_IVERILOG
        codes = sorted(set(re.findall(r"\b[LPRW]\d{4}\b", str(e))))
        return "+".join(codes) if codes else "uncoded: " + str(e)[:80]


def build_cell(mod, name, target):
    return _code(FEATURES[name](mod), target)


def text_cell(mod, name, target):
    text = PARITY[name][1]
    tb = mod.Testbench.from_source(text, "ngspice")
    return _code(tb, target)


def test_every_builder_has_a_text_twin():
    assert sorted(FEATURES) == sorted(set(PARITY) | NO_TWIN)


def test_every_feature_has_an_oracle_column():
    assert sorted(ORACLE) == sorted(PARITY)
    assert all(v == f"parity:{k}" for k, v in ORACLE.items())


@pytest.mark.parametrize("name", sorted(PARITY))
@pytest.mark.parametrize("target", TARGETS)
def test_build_equals_text(name, target):
    mod = ps_()
    got_text = text_cell(mod, name, target)
    gap = PARITY_GAP.get((name, target))
    if gap is not None:
        assert got_text != build_cell(mod, name, target), (
            f"{name} on {target}: PARITY_GAP {gap} passed unexpectedly; remove the marker"
        )
        pytest.xfail(f"PARITY_GAP: {gap}")
    assert got_text == build_cell(mod, name, target)


