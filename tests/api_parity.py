# Every `(name, target)` the round trip actually runs on: every written
# cell (`WRITES`) whose target is in the round trip's own domain (same
# family, no translation step: `_ROUND_TRIP_FAMILY`, which is inside
# `_NO_READER`'s complement already). No skip at runtime: a pair outside
# this list has no round-trip oracle to begin with (a refusal has no
# text; a foreign target's fidelity is Z1-Z3/Phase 5's gate, not this
# one's), so it is never parametrized, not silently passed over.
ROUND_TRIP_CASES = sorted(
    (name, t) for name in PARITY for t in TARGETS
    if t in _ROUND_TRIP_FAMILY and WRITES.get((name, t))
)


@pytest.mark.parametrize("name,target", ROUND_TRIP_CASES)
def test_store_round_trip(name, target):
    """`cell(from_spice(build.netlist(d), d)) == cell(build)` (D3): the
    store oracle. Catches state a builder keeps outside the text
    (python-api §2's `save_currents`, the subckts/options/temp `Circuit`
    drops)."""
    mod = ps_()
    tb = FEATURES[name](mod)
    built = _code(tb, target)
    text = tb.netlist(target)
    again = mod.Testbench.from_source(text, target)
    got = _code(again, target)
    gap = STORE_GAP.get((name, target))
    if gap is not None:
        assert got != built, f"{name} on {target}: STORE_GAP {gap} passed unexpectedly; remove the marker"
        pytest.xfail(f"STORE_GAP: {gap}")
    if name in STORE_TITLE_P8_312:
        assert got != built, f"{name} on {target}: P8-312 passed unexpectedly; remove it from STORE_TITLE_P8_312"
        pytest.xfail("P8-312: store.rs::read_deck doubles the title's '* ' on a second round trip")
    assert got == built


